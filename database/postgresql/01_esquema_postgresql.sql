-- NOVA SOUND: esquema adaptado de MySQL a PostgreSQL.
-- Ejecutar CONECTADO a la base nova_sounds (previamente creada con 00_crear_base.sql).
-- Los nombres no entrecomillados se almacenan en minusculas en PostgreSQL.
-- Preserva el modelo original, sin aplicar cambios funcionales de negocio.

BEGIN;

CREATE TABLE Roles (
    id_rol INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE Usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol INT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    usuario VARCHAR(50) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,

    CONSTRAINT FK_Usuarios_Roles
        FOREIGN KEY (id_rol)
        REFERENCES Roles(id_rol)
);

CREATE TABLE Clientes (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    mezcla_colores BOOLEAN NOT NULL
);

CREATE TABLE Modelos (
    id_modelo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE Colores (
    id_color INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE Linea (
    id_linea INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(20) NOT NULL
);

CREATE TABLE Turnos (
    id_turno INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hora_inicio TIME,
    hora_fin TIME
);

CREATE TABLE Areas (
    id_area INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE Ordenes (
    id_orden INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL,
    id_modelo INT NOT NULL,
    id_color INT NOT NULL,
    id_linea INT NOT NULL,
    cantidad INT NOT NULL,
    fecha_compromiso DATE,
    fecha_inicio TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Ordenes_Clientes
        FOREIGN KEY (id_cliente)
        REFERENCES Clientes(id_cliente),

    CONSTRAINT FK_Ordenes_Modelos
        FOREIGN KEY (id_modelo)
        REFERENCES Modelos(id_modelo),

    CONSTRAINT FK_Ordenes_Colores
        FOREIGN KEY (id_color)
        REFERENCES Colores(id_color),

    CONSTRAINT FK_Ordenes_Linea
        FOREIGN KEY (id_linea)
        REFERENCES Linea(id_linea)
);

CREATE TABLE Lote (
    id_lote INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden INT NOT NULL,
    cantidad_acordada INT NOT NULL,
    estado VARCHAR(30),
    fecha_creacion TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Lote_Ordenes
        FOREIGN KEY (id_orden)
        REFERENCES Ordenes(id_orden)
);

CREATE TABLE Ensamble (
    id_ensamble INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_turno INT NOT NULL,
    id_linea INT NOT NULL,
    id_lote INT NOT NULL,
    cantidad INT NOT NULL,
    fecha_ensamble TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Ensamble_Usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Ensamble_Turnos
        FOREIGN KEY (id_turno)
        REFERENCES Turnos(id_turno),

    CONSTRAINT FK_Ensamble_Linea
        FOREIGN KEY (id_linea)
        REFERENCES Linea(id_linea),

    CONSTRAINT FK_Ensamble_Lote
        FOREIGN KEY (id_lote)
        REFERENCES Lote(id_lote)
);

CREATE TABLE Entregas (
    id_entrega INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote INT NOT NULL,
    id_area_origen INT NOT NULL,
    id_area_destino INT NOT NULL,
    id_usuario_envia INT NOT NULL,
    id_usuario_recibe INT NULL,
    cantidad_enviada INT NOT NULL,
    cantidad_recibida INT NULL,
    fecha_entrega TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Entregas_Lote
        FOREIGN KEY (id_lote)
        REFERENCES Lote(id_lote),

    CONSTRAINT FK_Entregas_AreaOrigen
        FOREIGN KEY (id_area_origen)
        REFERENCES Areas(id_area),

    CONSTRAINT FK_Entregas_AreaDestino
        FOREIGN KEY (id_area_destino)
        REFERENCES Areas(id_area),

    CONSTRAINT FK_Entregas_UsuarioEnvia
        FOREIGN KEY (id_usuario_envia)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Entregas_UsuarioRecibe
        FOREIGN KEY (id_usuario_recibe)
        REFERENCES Usuarios(id_usuario)
);

CREATE TABLE Etiquetas (
    id_etiqueta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote INT NOT NULL,
    id_turno INT NOT NULL,
    id_usuario INT NOT NULL,
    id_entrega INT NULL,
    tipo_etiqueta VARCHAR(30),
    cantidad_registrada INT NOT NULL,
    fecha_generacion TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(30),

    CONSTRAINT FK_Etiquetas_Lote
        FOREIGN KEY (id_lote)
        REFERENCES Lote(id_lote),

    CONSTRAINT FK_Etiquetas_Turno
        FOREIGN KEY (id_turno)
        REFERENCES Turnos(id_turno),

    CONSTRAINT FK_Etiquetas_Usuario
        FOREIGN KEY (id_usuario)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Etiquetas_Entrega
        FOREIGN KEY (id_entrega)
        REFERENCES Entregas(id_entrega)
);

CREATE TABLE Unidades (
    id_unidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_color INT NOT NULL,
    id_linea INT NOT NULL,
    id_turno INT NOT NULL,
    id_caja INT NULL,
    id_lote INT NOT NULL,
    estado VARCHAR(30),
    fecha_hora TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    numero_serie VARCHAR(100) NULL,

    CONSTRAINT UQ_Unidades_NumeroSerie
        UNIQUE (numero_serie),

    CONSTRAINT FK_Unidades_Colores
        FOREIGN KEY (id_color)
        REFERENCES Colores(id_color),

    CONSTRAINT FK_Unidades_Linea
        FOREIGN KEY (id_linea)
        REFERENCES Linea(id_linea),

    CONSTRAINT FK_Unidades_Turnos
        FOREIGN KEY (id_turno)
        REFERENCES Turnos(id_turno),

    CONSTRAINT FK_Unidades_Lote
        FOREIGN KEY (id_lote)
        REFERENCES Lote(id_lote)
);

CREATE TABLE Pruebas (
    id_prueba INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INT NOT NULL,
    fecha TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    resultado VARCHAR(30),
    detalles_prueba VARCHAR(500),

    CONSTRAINT FK_Pruebas_Unidades
        FOREIGN KEY (id_unidad)
        REFERENCES Unidades(id_unidad)
);

CREATE TABLE Calidad (
    id_calidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INT NOT NULL,
    id_usuario INT NOT NULL,
    estado VARCHAR(30),
    fecha TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Calidad_Unidades
        FOREIGN KEY (id_unidad)
        REFERENCES Unidades(id_unidad),

    CONSTRAINT FK_Calidad_Usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES Usuarios(id_usuario)
);

CREATE TABLE CAT_DEFECTOS (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL
);

CREATE TABLE Defectos (
    id_defecto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_calidad INT NOT NULL,
    id_categoria INT NOT NULL,
    causa VARCHAR(200),

    CONSTRAINT FK_Defectos_Calidad
        FOREIGN KEY (id_calidad)
        REFERENCES Calidad(id_calidad),

    CONSTRAINT FK_Defectos_Categoria
        FOREIGN KEY (id_categoria)
        REFERENCES CAT_DEFECTOS(id_categoria)
);

CREATE TABLE Retrabajo (
    id_retrabajo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_unidad INT NOT NULL,
    id_calidad INT NOT NULL,
    descripcion VARCHAR(300),
    resultado VARCHAR(50),
    fecha TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_Retrabajo_Unidades
        FOREIGN KEY (id_unidad)
        REFERENCES Unidades(id_unidad),

    CONSTRAINT FK_Retrabajo_Calidad
        FOREIGN KEY (id_calidad)
        REFERENCES Calidad(id_calidad)
);

CREATE TABLE Embarques (
    id_embarque INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL,
    id_orden INT NOT NULL,
    fecha_salida TIMESTAMP WITHOUT TIME ZONE NULL,
    referencia VARCHAR(100),
    estado VARCHAR(30),

    CONSTRAINT FK_Embarques_Clientes
        FOREIGN KEY (id_cliente)
        REFERENCES Clientes(id_cliente),

    CONSTRAINT FK_Embarques_Ordenes
        FOREIGN KEY (id_orden)
        REFERENCES Ordenes(id_orden)
);

CREATE TABLE Cajas (
    id_caja INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INT NOT NULL,
    id_modelo INT NOT NULL,
    id_embarque INT NULL,
    estado VARCHAR(30),

    CONSTRAINT FK_Cajas_Clientes
        FOREIGN KEY (id_cliente)
        REFERENCES Clientes(id_cliente),

    CONSTRAINT FK_Cajas_Modelos
        FOREIGN KEY (id_modelo)
        REFERENCES Modelos(id_modelo),

    CONSTRAINT FK_Cajas_Embarques
        FOREIGN KEY (id_embarque)
        REFERENCES Embarques(id_embarque)
);

ALTER TABLE Unidades
ADD CONSTRAINT FK_Unidades_Cajas
FOREIGN KEY (id_caja)
REFERENCES Cajas(id_caja);

CREATE TABLE Objetivo_unidades (
    id_objetivo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_orden INT NOT NULL,
    id_linea INT NOT NULL,
    id_turno INT NOT NULL,
    cantidad_objetivo INT NOT NULL,
    fecha DATE,

    CONSTRAINT FK_Objetivo_Ordenes
        FOREIGN KEY (id_orden)
        REFERENCES Ordenes(id_orden),

    CONSTRAINT FK_Objetivo_Linea
        FOREIGN KEY (id_linea)
        REFERENCES Linea(id_linea),

    CONSTRAINT FK_Objetivo_Turnos
        FOREIGN KEY (id_turno)
        REFERENCES Turnos(id_turno)
);

CREATE TABLE CierresTurno (
    id_cierre INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_linea INT NOT NULL,
    id_turno INT NOT NULL,
    fecha TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    total_empacadas INT,
    total_retenidas INT,
    total_retrabajo INT,
    total_scrap INT,

    CONSTRAINT FK_Cierres_Usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Cierres_Linea
        FOREIGN KEY (id_linea)
        REFERENCES Linea(id_linea),

    CONSTRAINT FK_Cierres_Turnos
        FOREIGN KEY (id_turno)
        REFERENCES Turnos(id_turno)
);

CREATE TABLE Autorizacion (
    id_autorizacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario_solicita INT NOT NULL,
    id_usuario_autoriza INT NULL,
    id_referencia INT,
    tipo_referencia VARCHAR(50),
    motivo VARCHAR(300),
    estado VARCHAR(30),
    fecha_solicitud TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    fecha_autorizacion TIMESTAMP WITHOUT TIME ZONE NULL,

    CONSTRAINT FK_Autorizacion_UsuarioSolicita
        FOREIGN KEY (id_usuario_solicita)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Autorizacion_UsuarioAutoriza
        FOREIGN KEY (id_usuario_autoriza)
        REFERENCES Usuarios(id_usuario)
);

CREATE TABLE Bitacora_General (
    id_bitacora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INT NOT NULL,
    id_registro_afectado INT,
    id_autorizacion INT NULL,
    accion VARCHAR(50),
    tabla_afectada VARCHAR(100),
    valor_anterior VARCHAR(500),
    valor_nuevo VARCHAR(500),
    fecha_hora TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    motivo VARCHAR(500),

    CONSTRAINT FK_Bitacora_Usuarios
        FOREIGN KEY (id_usuario)
        REFERENCES Usuarios(id_usuario),

    CONSTRAINT FK_Bitacora_Autorizacion
        FOREIGN KEY (id_autorizacion)
        REFERENCES Autorizacion(id_autorizacion)
);

COMMIT;
